/**
 * Markup conventions:
 *   data-i18n="key"                 -> replaces textContent
 *   data-i18n-attr="alt:key;title:key2" -> replaces the listed attributes
 */
function setLanguage(lang) {
    const dict = translations[lang];
    if (!dict) return;

    document.documentElement.lang = lang;
    document.title = dict['meta.title'];

    document.querySelectorAll('[data-i18n]').forEach(el => {
        el.textContent = dict[el.dataset.i18n];
    });

    document.querySelectorAll('[data-i18n-attr]').forEach(el => {
        el.dataset.i18nAttr.split(';').forEach(pair => {
            const [attr, key] = pair.split(':').map(s => s.trim());
            if (attr && key) el.setAttribute(attr, dict[key]);
        });
    });

    // Highlight the active language in the switch
    document.querySelectorAll('.lang-opt').forEach(opt => {
        opt.classList.toggle('active', opt.dataset.lang === lang);
    });

    localStorage.setItem('lang', lang);
}

const initialLang = localStorage.getItem('lang')
    || (navigator.language.startsWith('es') ? 'es' : 'en');
setLanguage(initialLang);

document.getElementById('lang-toggle').addEventListener('click', () => {
    setLanguage(document.documentElement.lang === 'en' ? 'es' : 'en');
});
